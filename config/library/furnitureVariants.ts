// config/library/furnitureVariants.ts — LES VARIANTES DE COULEUR du grand
// catalogue de la Women's Library (lot 11 de docs/PLAN-womens-library.md,
// conference-website).
//
// UNE VARIANTE EST UNE CLÉ DU CATALOGUE À PART ENTIÈRE (`sofa_blue`) : achat,
// inventaire et placement ne changent pas, et aucune migration n'est
// nécessaire (`library_inventory.furniture_key`). Elle se rattache à une
// FAMILLE, la clé de sa base (`sofa`), dont elle reprend tout — empreinte,
// hauteur, catégorie, assise, calque — sauf la teinte : le pipeline du site la
// rend en changeant la matière du même modèle (`tools/library-assets`,
// `sources-furniture.json`, `iso_recolor.py`).
//
// PRIX : celui de la base. Une teinte ne vaut pas plus qu'une autre.
//
// `variant` est une CLÉ DE TEINTE (liste fermée ci-dessous) que l'interface
// traduit ; la base d'une famille à variantes a aussi la sienne
// (`LIBRARY_FAMILY_COLORS`), pour que le sélecteur la nomme.
//
// Module PUR (aucun import) : il est recopié tel quel dans le site.

