/** Une variante : sa clé, sa famille (la clé de sa base), sa teinte. */
export type FurnitureVariantSpec = {
  key: string;
  family: string;
  variant: FurnitureColor;
};

const v = (
  family: string,
  variant: FurnitureColor,
  key = `${family}_${variant}`
): FurnitureVariantSpec => ({ key, family, variant });

